def infer_n2k2(con):
    out=dict(con)
    if 'M2' in con and 'S2' in con:
        aM2,gM2=con['M2']; aS2,gS2=con['S2']
        if 'N2' not in out: out['N2']=(round(0.19*aM2,4),(gM2-0.536*(gS2-gM2))%360)
        if 'K2' not in out: out['K2']=(round(0.27*aS2,4),gS2%360)
    return out

def swcorr(con):
    """ATT-S.W.-Corrections: M4/M6 stehen in `con` als DRUCKWERTE (F4,f4)/(F6,f6).
    F4/F6 sind FAKTOREN (nicht Amplituden): H4 = F4*H_M2^2, g4 = 2*g_M2 + f4
    (analog H6 = F6*H_M2^3, g6 = 3*g_M2 + f6). Empirisch validiert gegen
    Bordeaux (M4 0.285 m) und Lisboa (UTide M4 0.045 m); Faktor-Deutung noetig,
    weil z.B. Sete F4=1.331 als Amplitude unmoeglich waere."""
    out=dict(con)
    if 'M2' in con:
        H,g=con['M2']
        if 'M4' in con:
            F4,f4=con['M4']; out['M4']=(round(F4*H*H,4),round((2*g+f4)%360,2))
        if 'M6' in con:
            F6,f6=con['M6']; out['M6']=(round(F6*H**3,4),round((3*g+f6)%360,2))
    return out

